from gui.Import.ImportPPTXDialog import ImportPPTXDialog


class ImportLaTeXDialog(ImportPPTXDialog):
    """
    Imports LaTeX generated by BeamerQt into an import folder holding the new
    .bqt file and the images and plot data it needs. The theme and all the
    settings come from the file, so the PowerPoint options are hidden.
    """

    SourceName = "LaTeX file"
    SourceFilter = "LaTeX files (*.tex)"
    SourceExtension = ".tex"

    def __init__(self, WorkDirectory, Config, parent=None):

        super(ImportLaTeXDialog, self).__init__(WorkDirectory, Config, parent)

        self.setWindowTitle("Import LaTeX (experimental)")
        self.warningLabel.setText("This importer is experimental and reads LaTeX generated by BeamerQt: "
                                  "review the result before using it.")
        self.pptxLabel.setText("LaTeX file")
        self.contentGroup.hide()
        self.appearanceGroup.hide()
        self.adjustSize()


    def PreviewFolders(self):
        return ["images", "data"]


    def RunImport(self, source, Document, folder):
        from core.importlatex import BeamerLatexImport
        return BeamerLatexImport().Import(source, Document, folder)
