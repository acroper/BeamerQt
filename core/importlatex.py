# Reads back LaTeX generated by BeamerQt, using the markers it writes (see
# core/latexmarkers.py). Each item marker holds the item's saved XML: if the
# item's LaTeX was not edited the item is restored exactly, otherwise the
# edited LaTeX is parsed, or kept as raw LaTeX in a Text item.

import os
import re
import json
import shutil

from PyQt6.QtGui import QTextDocument

from core.beamerBlock import BeamerBlock
from core.template import BeamerTemplate
from core.latexmarkers import PREFIX, ParseMarker, DecodeXML
from core.beamerpptx import BeamerPPT, Paragraph


BLOCK_ENVS = {"block": "Normal", "exampleblock": "Example", "alertblock": "Alert"}

TABLE_RULES = ("\\hline", "\\toprule", "\\midrule", "\\bottomrule")


def Normalize(text):
    return " ".join(text.split())


def ReadGroup(text, start):
    # Contents of the {...} group starting at text[start], and the index after it
    depth = 0
    i = start
    while i < len(text):
        ch = text[i]
        if ch == "\\":
            i += 2
            continue
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                return text[start + 1:i], i + 1
        i += 1
    return None, start


def SkipSpaces(text, i):
    while i < len(text) and text[i] in " \t\n":
        i += 1
    return i


def CommandArg(text, command):
    """(optional, mandatory) arguments of the last \\command in text, or (None, None)."""
    matches = list(re.finditer(re.escape(command) + r"(?![A-Za-z])", text))
    if not matches:
        return None, None
    i = SkipSpaces(text, matches[-1].end())
    optional = None
    if i < len(text) and text[i] == "[":
        end = text.find("]", i)
        if end < 0:
            return None, None
        optional = text[i + 1:end]
        i = SkipSpaces(text, end + 1)
    if i < len(text) and text[i] == "{":
        return optional, ReadGroup(text, i)[0]
    return optional, None


def StripComments(text):
    # Remove % comments; a line holding only a comment disappears (no paragraph break)
    lines = []
    for line in text.split("\n"):
        match = re.search(r"(?<!\\)%", line)
        if match:
            line = line[:match.start()]
            if not line.strip():
                continue
        lines.append(line)
    return "\n".join(lines)


def FindEnvEnd(text, start, name):
    """(start, end) of the \\end{name} closing an environment whose body starts at start."""
    depth = 1
    for match in re.finditer(r"\\(begin|end)\{" + re.escape(name) + r"\}", text[start:]):
        depth += 1 if match.group(1) == "begin" else -1
        if depth == 0:
            return start + match.start(), start + match.end()
    return -1, -1


def SkipArgs(text, i, brackets="<["):
    # Skip optional <overlay> and [options] arguments
    closing = {"<": ">", "[": "]"}
    i = SkipSpaces(text, i)
    while i < len(text) and text[i] in brackets:
        end = text.find(closing[text[i]], i)
        if end < 0:
            break
        i = SkipSpaces(text, end + 1)
    return i


def StatementSpans(text, command):
    """(start, end) of every \\command in text, with its [..], <..> and {..} arguments."""
    spans = []
    for match in re.finditer(re.escape(command) + r"(?![A-Za-z])", text):
        j = SkipArgs(text, match.end())
        while j < len(text) and text[j] == "{":
            group, k = ReadGroup(text, j)
            if group is None:
                break
            j = SkipArgs(text, k)
        spans.append((match.start(), j))
    return spans


def BraceDepth(text, pos):
    # Depth of {..} groups at pos (e.g. a \frame inside \AtBeginSubsection{..} is at depth 1)
    return BraceBalance(text[:pos])


def BraceBalance(text):
    return len(re.findall(r"(?<!\\)\{", text)) - len(re.findall(r"(?<!\\)\}", text))


def TopLevelSearch(pattern, text, pos=0):
    """First match of pattern at or after pos that is not inside a {..} group."""
    for match in re.compile(pattern).finditer(text, pos):
        if BraceDepth(text, match.start()) <= 0:
            return match
    return None


def RemoveSpans(text, spans):
    out = []
    pos = 0
    for start, end in sorted(spans):
        if start >= pos:
            out.append(text[pos:start])
            pos = end
    out.append(text[pos:])
    return "".join(out)


# Read into BeamerQt's front matter fields
FIELD_COMMANDS = ("\\title", "\\subtitle", "\\author")

# Other document fields: copied to the preamble, active
DOCUMENT_COMMANDS = ("\\date", "\\institute", "\\logo", "\\titlegraphic", "\\subject", "\\keywords")

# Handled by BeamerQt itself, never copied: in the preamble, and before the first frame
HANDLED_PREAMBLE = ("\\documentclass", "\\usetheme")
HANDLED_BODY = ("\\makebeamertitle", "\\maketitle")

IMPORTED_HEADER = "% Imported commands, uncomment to activate"

MATH_ENVS = {"equation": "", "equation*": "", "displaymath": "", "multline": "", "multline*": "",
             "align": "aligned", "align*": "aligned", "gather": "gathered", "gather*": "gathered"}

WRAPPER_ENVS = ("center", "flushleft", "flushright", "figure", "figure*", "table", "table*")

LIST_ENVS = ("itemize", "enumerate", "description")

IMAGE_EXTENSIONS = ("", ".pdf", ".png", ".jpg", ".jpeg")


class BeamerLatexImport:

    def Import(self, filename, Document, folder):
        """
        Fill Document from a LaTeX file generated by BeamerQt. Files the items
        need (images, plot data) are copied under folder. Returns a list of
        messages about content that was approximated.
        """
        self.LatexFolder = os.path.dirname(os.path.abspath(filename))
        self.Folder = folder
        self.Messages = []

        with open(filename, encoding="utf-8", errors="replace") as f:
            text = f.read()

        if "\\begin{document}" not in text:
            raise ValueError("This is not a complete LaTeX document (no \\begin{document}).")

        head, _, body = text.partition("\\begin{document}")

        # Plot previews are stored in the current document's media folder
        from core.beamerDocument import beamerDocument
        previous = getattr(beamerDocument, "Current", None)
        beamerDocument.Current = Document
        try:
            if PREFIX in text:
                self.ReadHead(head, Document)
                self.ReadBody(body, Document)
            else:
                # Not generated by BeamerQt: read the structure from the LaTeX itself
                self.ReadPlainHead(head, body, Document)
                self.ReadPlainBody(body, Document)
        finally:
            beamerDocument.Current = previous

        return self.Messages


    def Subfolder(self, name):
        path = os.path.join(self.Folder, name)
        os.makedirs(path, exist_ok=True)
        return path


    # ---------- Front matter and theme ----------

    def ReadHead(self, head, Document):
        fm = Document.FrontMatter

        for line in head.split("\n"):
            marker = ParseMarker(line)
            if marker is None:
                continue
            kind, attrs = marker
            if kind == "frontmatter":
                fm.ReadXMLContent(DecodeXML(attrs["data"]))
            elif kind == "template":
                self.LoadTemplate(attrs.get("name", ""), Document)

        # Values in the LaTeX win, so edits are kept
        short, title = CommandArg(head, "\\title")
        if title is not None:
            fm.Title, fm.ShortTitle = title, short or ""
        subtitle = CommandArg(head, "\\subtitle")[1]
        if subtitle is not None:
            fm.Subtitle = subtitle
        short, author = CommandArg(head, "\\author")
        if author is not None:
            fm.Author, fm.ShortAuthor = author, short or ""

        options = re.search(r"\\documentclass\[([^\]]*)\]", head)
        if options:
            fm.AspectRatio = "169" if "aspectratio=169" in options.group(1) else "43"


    def LoadTemplate(self, name, Document):
        for file in sorted(os.listdir("templates")):
            if file.endswith("xml"):
                templ = BeamerTemplate()
                templ.ReadXMLFile(os.path.join("templates", file))
                if templ.Name == name:
                    Document.Template = templ
                    return
        self.Messages.append("Theme '" + name + "' not found, the default theme is used")


    # ---------- Slides, columns, blocks and items ----------

    def ReadBody(self, body, Document):
        slide = None
        column = 0
        block = None
        item = None
        item_lines = []
        pending = []
        last = None

        for line in body.split("\n"):
            marker = ParseMarker(line)

            if item is not None:
                if marker is None:
                    item_lines.append(line)
                    continue
                self.AddItem(block, item, item_lines)
                item = None
                if marker[0] == "end":
                    continue

            if marker is None:
                pending.append(line)
                continue

            self.Flush(last, pending)
            pending = []

            kind, attrs = marker
            if kind == "frame":
                slide = self.NewSlide(Document, attrs)
                column = 0
                block = None
                last = ("frame", slide)
            elif kind == "column":
                column = min(1, max(0, int(attrs.get("n", "0"))))
                last = None
            elif kind == "block" and slide is not None:
                block = self.NewBlock(attrs)
                slide.Columns[column].append(block)
                last = ("block", block)
            elif kind == "item" and block is not None:
                item = attrs
                item_lines = []
                last = None

        if item is not None:
            self.AddItem(block, item, item_lines)
        self.Flush(last, pending)


    def NewSlide(self, Document, attrs):
        slide = Document.NewSlide()
        slide.CurrentLayout = attrs.get("layout", "layout_standard")
        slide.LeftColumnProportion = int(float(attrs.get("proportion", "100")))
        slide.TitleMode = attrs.get("titlemode", "Normal")
        slide.SectionLabel = attrs.get("section", "")
        slide.Subtitle = attrs.get("subtitle", "")
        slide.TitleVisible = attrs.get("visible", "True") == "True"
        return slide


    def NewBlock(self, attrs):
        block = BeamerBlock()
        block.BlockType = attrs.get("type", "Normal")
        block.Title = attrs.get("title", "")
        block.ColumnCount = int(attrs.get("columns", "1"))
        try:
            block.ColumnProportions = json.loads(attrs.get("proportions", "[100, 100, 100, 100]"))
        except ValueError:
            pass
        return block


    def Flush(self, last, lines):
        # LaTeX between a frame or block marker and the next marker: read titles from it
        if last is None:
            return
        text = "\n".join(lines)
        kind, obj = last

        if kind == "frame":
            section = CommandArg(text, "\\section")[1]
            subsection = CommandArg(text, "\\subsection")[1]
            if section is not None:
                obj.TitleMode, obj.SectionLabel = "Section", section
            elif subsection is not None:
                obj.TitleMode, obj.SectionLabel = "Subsection", subsection
            else:
                obj.TitleMode = "Normal"

            title = CommandArg(text, "\\sectionText")[1]
            if title is None:
                begin = text.find("\\begin{frame}")
                if begin >= 0:
                    i = SkipSpaces(text, begin + len("\\begin{frame}"))
                    if i < len(text) and text[i] == "{":
                        title = ReadGroup(text, i)[0]
            if title is not None:
                obj.Title = title

        elif kind == "block":
            env = re.search(r"\\begin\{(block|exampleblock|alertblock)\}", text)
            if env:
                obj.BlockType = BLOCK_ENVS[env.group(1)]
                i = SkipSpaces(text, env.end())
                if i < len(text) and text[i] == "{":
                    title = ReadGroup(text, i)[0]
                    if title is not None:
                        obj.Title = title


    def AddItem(self, block, attrs, lines):
        latex = "\n".join(lines).strip()
        item = None
        try:
            element = DecodeXML(attrs["data"])
            item = block.GetItemType(element.get("ItemType"))
            item.ReadXMLContent(element)
            item = self.Restore(item, latex)
        except Exception as e:
            item = None
            self.Messages.append("Item could not be restored (" + str(e) + ")")

        if item is None and latex:
            # Keep the LaTeX as it is
            item = block.GetItemType("Text")
            item.Text = latex
            self.Messages.append("Edited " + attrs.get("type", "item") + " kept as LaTeX code: "
                                 + Normalize(latex)[:40])

        if item is not None:
            block.SubBlocks.append(item)


    def Restore(self, item, latex):
        """The item, updated with the edits found in its LaTeX, or None if they can't be read."""
        if item.Type == "Image":
            return self.RestoreImage(item, latex)
        if item.Type == "Plot":
            return self.RestorePlot(item, latex)

        if Normalize("\n".join(item.GenLatex())) == Normalize(latex):
            return item

        if item.Type == "EquationQT":
            equation = re.fullmatch(r"\\\[(.*)\\\]", latex, re.S)
            if equation is None:
                return None
            item.Latex = equation.group(1).strip()
            return item

        if item.Type == "Text":
            if latex.endswith("\\phantom{-}"):
                latex = latex[:-len("\\phantom{-}")]
            item.Text = latex.replace("\\\\ \n", "\n")
            return item

        if item.Type == "RTF":
            item.RTF = QTextDocument()
            BeamerPPT().FillDocument(item.RTF, self.ParseRichText(latex), escape=False)
            return item

        if item.Type == "Table":
            return self.ParseTable(item, latex)

        return None


    # ---------- Item readers ----------

    def ParseRichText(self, latex):
        # Paragraphs and nested lists with \textbf, \textit and \emph. Reads the rich
        # text item's own output as well as hand-written LaTeX.
        latex = latex.replace("\\phantom{-}", "")
        latex = re.sub(r"\\pause(?![A-Za-z])(\{\})?", "", latex)
        # List structure on lines of its own; overlay specs (<2->) dropped
        latex = re.sub(r"\\(begin|end)\{(itemize|enumerate|description)\}(<[^>]*>)?(\[[^\]]*\])?",
                       lambda m: "\n\\" + m.group(1) + "{" + m.group(2) + "}\n", latex)
        latex = re.sub(r"\\item(?![A-Za-z])(<[^>]*>)?", "\n\\\\item", latex)

        paragraphs = []
        stack = []
        current = None

        def close():
            nonlocal current
            if current is not None:
                level, env, parts = current
                text = " ".join(" ".join(parts).split())
                text = re.sub(r"(\s*\\\\)+$", "", text).strip()
                if text:
                    paragraphs.append(Paragraph(level, env, self.Segments(text)))
                current = None

        for line in latex.split("\n"):
            line = line.strip()
            if not line:
                close()
                continue
            structure = re.fullmatch(r"\\(begin|end)\{(itemize|enumerate|description)\}", line)
            if structure:
                close()
                if structure.group(1) == "begin":
                    stack.append("enumerate" if structure.group(2) == "enumerate" else "itemize")
                elif stack:
                    stack.pop()
                continue
            if line.startswith("\\item") and stack:
                close()
                rest = line[5:].lstrip()
                if rest.startswith("["):
                    # description label, shown in bold
                    end = rest.find("]")
                    if end > 0:
                        rest = "\\textbf{" + rest[1:end] + "} " + rest[end + 1:].lstrip()
                current = (len(stack) - 1, stack[-1], [rest])
            elif current is None:
                current = (0, None, [line])
            else:
                current[2].append(line)
        close()
        return paragraphs


    def Segments(self, text, bold=False, italic=False):
        segments = []
        while text:
            match = re.search(r"\\(textbf|textit|emph)\{", text)
            if match is None:
                segments.append(("text", text, bold, italic))
                break
            if match.start() > 0:
                segments.append(("text", text[:match.start()], bold, italic))
            inner, end = ReadGroup(text, match.end() - 1)
            if inner is None:
                segments.append(("text", text[match.start():], bold, italic))
                break
            segments.extend(self.Segments(inner, bold or match.group(1) == "textbf",
                                          italic or match.group(1) != "textbf"))
            text = text[end:]
        return segments


    def ParseTable(self, item, latex):
        begin = re.search(r"\\begin\{tabular\}", latex)
        end = latex.rfind("\\end{tabular}")
        if begin is None or end < 0:
            return None
        spec, start = ReadGroup(latex, SkipSpaces(latex, begin.end()))
        if spec is None:
            return None

        rows = []
        for row in latex[start:end].split("\\\\"):
            for rule in TABLE_RULES:
                row = row.replace(rule, "")
            row = re.sub(r"\\rowcolor\{[^}]*\}", "", row).strip()
            if not row:
                continue
            cells = []
            for cell in re.split(r"(?<!\\)&", row):
                cell = cell.strip()
                bold = re.fullmatch(r"\\textbf\{(.*)\}", cell, re.S)
                cells.append(bold.group(1) if bold else cell)
            rows.append(cells)

        if not rows:
            return None
        item.rows = len(rows)
        item.cols = max(len(r) for r in rows)
        item.table = [r + [""] * (item.cols - len(r)) for r in rows]
        return item


    def RestoreImage(self, item, latex):
        graphics = re.search(r"\\includegraphics(\[[^\]]*\])?\{", latex)
        if graphics is None:
            return None
        path = ReadGroup(latex, graphics.end() - 1)[0] or ""
        width = re.search(r"width=([\d.]+)\\linewidth", graphics.group(1) or "")
        if width:
            item.Width = int(round(float(width.group(1)) * 100))

        # The LaTeX folder holds a copy named <name>_<uuid>; the original is preferred
        copied = item.uuid in os.path.basename(path)
        if copied and os.path.exists(item.image_path):
            return item

        source = path if os.path.isabs(path) else os.path.join(self.LatexFolder, path)
        if source.endswith(".svg.pdf") and os.path.exists(source[:-4]):
            source = source[:-4]

        if os.path.exists(source):
            dest = os.path.join(self.Subfolder("images"), os.path.basename(source))
            if os.path.abspath(source) != os.path.abspath(dest):
                shutil.copy2(source, dest)
            item.image_path = dest
        else:
            self.Messages.append("Image not found: " + path)
        return item


    def RestorePlot(self, item, latex):
        from gui.ContentItems.Plot import csv_parser, plot_compiler

        # The data: the original CSV, or the copy written next to the LaTeX
        if not os.path.exists(item.CsvPath):
            copy = os.path.join(self.LatexFolder, item.CsvFilename())
            if os.path.exists(copy):
                dest = os.path.join(self.Subfolder("data"), item.CsvFilename())
                shutil.copy2(copy, dest)
                item.CsvPath = dest
                item.CsvDelimiter, item.CsvDecimal, item.CsvHasHeader = ",", ".", True
            else:
                self.Messages.append("Plot data not found: " + item.CsvFilename())

        resolved = ""
        if item.LatexCode.strip():
            resolved = csv_parser.resolve_tags(item.LatexCode, item.Series, item.CsvPath,
                                               item.CsvDelimiter, item.CsvDecimal, item.CsvHasHeader,
                                               item.Bins, xtick_step=item.XTickStep)
        if Normalize(resolved) != Normalize(latex):
            item.LatexCode = latex

        if item.LatexCode.strip():
            plot_compiler.compile_and_store_preview(item)
        return item


    # ---------- LaTeX without markers ----------

    def ReadPlainHead(self, head, body, Document):
        fm = Document.FrontMatter
        head = StripComments(head)

        # Some tools (e.g. LyX) write \title, \author... after \begin{document}
        front = StripComments(body)
        first = TopLevelSearch(r"\\begin\{frame\}|\\frame(?![A-Za-z])|\\(sub)?section(?![A-Za-z])", front)
        if first:
            front = front[:first.start()]
        fields = head + "\n" + front

        short, title = CommandArg(fields, "\\title")
        if title is not None:
            fm.Title, fm.ShortTitle = " ".join(title.split()), short or ""
        subtitle = CommandArg(fields, "\\subtitle")[1]
        if subtitle is not None:
            fm.Subtitle = " ".join(subtitle.split())
        short, author = CommandArg(fields, "\\author")
        if author is not None:
            fm.Author, fm.ShortAuthor = " ".join(author.split()), short or ""

        options = re.search(r"\\documentclass\[([^\]]*)\]", head)
        if options:
            fm.AspectRatio = "169" if "aspectratio=169" in options.group(1) else "43"

        theme = CommandArg(head, "\\usetheme")[1]
        if theme:
            self.LoadTheme(theme.strip(), Document)

        paths = CommandArg(head, "\\graphicspath")[1] or ""
        self.GraphicsPaths = re.findall(r"\{([^{}]*)\}", paths)

        # Document fields (date, institute...) go to the preamble active. Everything
        # else goes commented out, so it can never collide with BeamerQt's commands.
        active = []
        rest = []
        for text, handled in ((head, HANDLED_PREAMBLE), (front, HANDLED_BODY)):
            spans = []
            for command in FIELD_COMMANDS + handled:
                spans += StatementSpans(text, command)
            for command in DOCUMENT_COMMANDS:
                for start, end in StatementSpans(text, command):
                    active.append(text[start:end].strip())
                    spans.append((start, end))
            rest += [line.rstrip() for line in RemoveSpans(text, spans).split("\n") if line.strip()]

        preamble = list(active)
        if rest:
            preamble += ["", IMPORTED_HEADER] + ["% " + line for line in rest]
        if preamble:
            fm.Preamble = "\n".join(preamble).strip()
        if active:
            self.Messages.append("Date, institute and similar fields were copied to the front matter preamble")
        if rest:
            self.Messages.append("Other preamble commands were copied commented out to the front matter preamble")


    def LoadTheme(self, name, Document):
        # A theme whose \usetheme is name, or whose name is name
        templates = []
        for file in sorted(os.listdir("templates")):
            if file.endswith("xml"):
                templ = BeamerTemplate()
                templ.ReadXMLFile(os.path.join("templates", file))
                templates.append(templ)
        for match in (lambda t: (t.UseTheme or "").lower() == name.lower(),
                      lambda t: t.Name.lower() == name.lower()):
            for templ in templates:
                if match(templ):
                    Document.Template = templ
                    return
        self.Messages.append("Theme '" + name + "' not found, the default theme is used")


    def ReadPlainBody(self, body, Document):
        body = StripComments(body.split("\\end{document}")[0])
        # Frames nested in other commands (e.g. \AtBeginSubsection{\frame{..}}) are not slides
        pattern = r"\\(section|subsection)\*?(?![A-Za-z])|\\begin\{frame\}|\\frame(?![A-Za-z])"
        section = None
        i = 0
        while True:
            match = TopLevelSearch(pattern, body, i)
            if match is None:
                break

            if match.group(1):
                j = SkipArgs(body, match.end(), "[")
                if j < len(body) and body[j] == "{":
                    label, j = ReadGroup(body, j)
                    section = ("Section" if match.group(1) == "section" else "Subsection",
                               " ".join((label or "").split()))
                i = max(j, match.end())
                continue

            if match.group(0) == "\\begin{frame}":
                end, after = FindEnvEnd(body, match.end(), "frame")
                if end < 0:
                    end = after = len(body)
                content = body[match.end():end]
                i = after
            else:
                # \frame{...}
                j = SkipArgs(body, match.end())
                if j >= len(body) or body[j] != "{":
                    i = j
                    continue
                content, i = ReadGroup(body, j)
                content = content or ""

            if self.PlainFrame(content, Document, section):
                section = None


    def PlainFrame(self, content, Document, section):
        """Add a slide for a frame; False for title page frames, which are skipped."""
        # \begin{frame}<overlay>[options]{title}{subtitle}
        j = SkipArgs(content, 0)
        title = subtitle = ""
        if content[j:j + 1] == "{":
            title, j = ReadGroup(content, j)
            k = SkipSpaces(content, j)
            if content[k:k + 1] == "{":
                subtitle, j = ReadGroup(content, k)
        body = content[j:]

        for command in ("\\frametitle", "\\framesubtitle"):
            value = CommandArg(body, command)[1]
            if value is not None:
                if command == "\\frametitle":
                    title = value
                else:
                    subtitle = value
                body = self.RemoveCommand(body, command)

        if re.search(r"\\(titlepage|maketitle)(?![A-Za-z])", body):
            self.Messages.append("Title page frame skipped (BeamerQt creates it from the front matter)")
            return False

        slide = Document.NewSlide()
        slide.Title = " ".join((title or "").split())
        slide.Subtitle = " ".join((subtitle or "").split())
        if section:
            slide.TitleMode, slide.SectionLabel = section

        columns = re.search(r"\\begin\{columns\}", body)
        if columns is None:
            self.AddBlocks(slide, 0, body)
            return True

        end, after = FindEnvEnd(body, columns.end(), "columns")
        if end < 0:
            end = after = len(body)
        parts = self.SplitColumns(body[columns.end():end])

        self.AddBlocks(slide, 0, body[:columns.start()])
        if parts:
            self.AddBlocks(slide, 0, parts[0][1])
        for width, text in parts[1:]:
            self.AddBlocks(slide, 1, text)
        if body[after:].strip():
            self.Messages.append("Slide '" + slide.Title + "': content below the columns was put in the left column")
            self.AddBlocks(slide, 0, body[after:])

        if len(parts) > 1:
            slide.CurrentLayout = "layout_2cols"
            slide.LeftColumnProportion = self.ColumnProportion(parts[0][0], parts[1][0])
        return True


    def RemoveCommand(self, text, command):
        # text without every \command[..]{..}
        while True:
            match = re.search(re.escape(command) + r"(?![A-Za-z])", text)
            if match is None:
                return text
            j = SkipArgs(text, match.end())
            if j < len(text) and text[j] == "{":
                j = ReadGroup(text, j)[1]
            text = text[:match.start()] + text[j:]


    def SplitColumns(self, text):
        """[(width, content)] for \\begin{column}{w}...\\end{column} or \\column{w} ..."""
        text = text[SkipArgs(text, 0):]
        parts = []
        if "\\begin{column}" in text:
            for match in re.finditer(r"\\begin\{column\}", text):
                j = SkipArgs(text, match.end())
                width = ""
                if text[j:j + 1] == "{":
                    width, j = ReadGroup(text, j)
                end, _ = FindEnvEnd(text, match.end(), "column")
                if end > 0:
                    parts.append((width or "", text[j:end]))
        else:
            matches = list(re.finditer(r"\\column(?![A-Za-z])", text))
            for k, match in enumerate(matches):
                j = SkipArgs(text, match.end(), "[")
                width = ""
                if text[j:j + 1] == "{":
                    width, j = ReadGroup(text, j)
                stop = matches[k + 1].start() if k + 1 < len(matches) else len(text)
                parts.append((width or "", text[j:stop]))
        return parts


    def ColumnProportion(self, left, right):
        def fraction(width):
            match = re.match(r"\s*([\d.]*)\s*\\(textwidth|linewidth|columnwidth|paperwidth)", width or "")
            if match is None:
                return None
            return float(match.group(1) or 1)
        a, b = fraction(left), fraction(right)
        proportion = 100 * a / (a + b) if a and b else (100 * a if a else 50)
        return int(min(75, max(25, 5 * round(proportion / 5))))


    def AddBlocks(self, slide, column, text):
        # Beamer blocks become blocks; content between them goes in boxless "Simple" blocks
        pos = 0
        for match in re.finditer(r"\\begin\{(block|exampleblock|alertblock)\}", text):
            if match.start() < pos:
                continue
            self.AddContent(slide, column, "Simple", "", text[pos:match.start()])
            j = SkipArgs(text, match.end(), "<")
            title = ""
            if text[j:j + 1] == "{":
                title, j = ReadGroup(text, j)
            end, after = FindEnvEnd(text, match.end(), match.group(1))
            if end < 0:
                end = after = len(text)
            self.AddContent(slide, column, BLOCK_ENVS[match.group(1)], " ".join((title or "").split()), text[j:end])
            pos = after
        self.AddContent(slide, column, "Simple", "", text[pos:])


    def AddContent(self, slide, column, block_type, title, text):
        block = BeamerBlock()
        block.BlockType = block_type
        block.Title = title
        items = self.ContentItems(block, text)
        if not items and not title:
            return

        slide.Columns[column].append(block)
        for k, item in enumerate(items):
            if k > 0:
                # A block lays several items out in a row, so each item gets its own block
                block = BeamerBlock()
                block.BlockType = block_type
                slide.Columns[column].append(block)
            block.SubBlocks.append(item)


    def ContentItems(self, block, text):
        """Items for the content of a block, in order."""
        items = []
        rich = []

        def flush():
            content = "".join(rich).strip()
            rich.clear()
            paragraphs = self.ParseRichText(content) if content else []
            if paragraphs:
                item = block.GetItemType("RTF")
                BeamerPPT().FillDocument(item.RTF, paragraphs, escape=False)
                items.append(item)

        def raw(latex):
            item = block.GetItemType("Text")
            item.Text = latex.strip()
            items.append(item)

        depth = 0
        i = 0
        n = len(text)
        while i < n:
            ch = text[i]

            if ch == "\\" and depth > 0:
                rich.append(text[i:i + 2])
                i += 2
                continue

            if ch == "\\":
                rest = text[i:]
                env = re.match(r"\\begin\{([A-Za-z*]+)\}", rest)

                if rest.startswith("\\["):
                    end = text.find("\\]", i + 2)
                    if end < 0:
                        end = n
                    flush()
                    items.append(self.PlainEquation("", text[i + 2:end], block))
                    i = end + 2
                    continue

                if env:
                    name = env.group(1)
                    start = i + env.end()
                    end, after = FindEnvEnd(text, start, name)
                    if end < 0:
                        end = after = n
                    if name in LIST_ENVS:
                        rich.append(text[i:after])
                    else:
                        flush()
                        if name in MATH_ENVS:
                            items.append(self.PlainEquation(name, text[start:end], block))
                        elif name in WRAPPER_ENVS:
                            items.extend(self.ContentItems(block, text[SkipArgs(text, start, "["):end]))
                        elif name == "tabular":
                            table = text[i:after]
                            item = None
                            if not re.search(r"\\multi(column|row)", table):
                                item = self.ParseTable(block.GetItemType("Table"), table)
                            if item is None:
                                raw(table)
                                self.Messages.append("Table kept as LaTeX code (merged cells)")
                            else:
                                items.append(item)
                        else:
                            raw(text[i:after])
                    i = after
                    continue

                graphics = re.match(r"\\includegraphics\s*(<[^>]*>)?\s*(\[[^\]]*\])?\s*\{", rest)
                if graphics:
                    path, after = ReadGroup(text, i + graphics.end() - 1)
                    flush()
                    items.append(self.PlainImage(path or "", graphics.group(2) or "", text[i:after], block))
                    i = after
                    continue

                caption = re.match(r"\\caption\s*(\[[^\]]*\])?\s*\{", rest)
                if caption:
                    value, after = ReadGroup(text, i + caption.end() - 1)
                    if items and items[-1].Type == "Image" and not "".join(rich).strip():
                        items[-1].PostText = " ".join((value or "").split())
                    else:
                        rich.append(value or "")
                    i = after
                    continue

                # Layout commands BeamerQt handles itself
                layout = re.match(r"\\(pause|centering|vfill|hfill|medskip|bigskip|smallskip|noindent|par)"
                                  r"(?![A-Za-z])(\{\})?", rest)
                if layout:
                    i += layout.end()
                    continue
                spacing = re.match(r"\\(vspace|hspace|label)\*?\s*\{", rest)
                if spacing:
                    i = ReadGroup(text, i + spacing.end() - 1)[1]
                    continue

                rich.append(text[i:i + 2])
                i += 2
                continue

            if ch == "$" and depth == 0 and text.startswith("$$", i):
                end = text.find("$$", i + 2)
                if end < 0:
                    end = n
                flush()
                items.append(self.PlainEquation("", text[i + 2:end], block))
                i = end + 2
                continue

            if ch == "{":
                depth += 1
            elif ch == "}":
                depth = max(0, depth - 1)
            rich.append(ch)
            i += 1

        flush()
        return items


    def PlainEquation(self, env, latex, block):
        latex = re.sub(r"\\(label\{[^}]*\}|nonumber|notag)", "", latex).strip()
        wrapper = MATH_ENVS.get(env, "")
        if wrapper:
            latex = "\\begin{" + wrapper + "} " + latex + " \\end{" + wrapper + "}"
        item = block.GetItemType("EquationQT")
        item.Latex = latex
        return item


    def PlainImage(self, path, options, latex, block):
        source = self.FindImage(path.strip())
        if source is None:
            self.Messages.append("Image not found, kept as LaTeX code: " + path)
            item = block.GetItemType("Text")
            item.Text = latex
            return item

        dest = os.path.join(self.Subfolder("images"), os.path.basename(source))
        if os.path.abspath(source) != os.path.abspath(dest):
            shutil.copy2(source, dest)

        item = block.GetItemType("Image")
        item.image_path = dest
        width = re.search(r"width\s*=\s*([\d.]*)\s*\\(textwidth|linewidth|columnwidth)", options)
        if width:
            item.Width = int(min(100, max(10, round(float(width.group(1) or 1) * 100))))
        return item


    def FindImage(self, path):
        # \includegraphics finds files relative to the .tex file or \graphicspath,
        # often without an extension
        if os.path.isabs(path):
            folders = [""]
        else:
            folders = [self.LatexFolder] + [os.path.join(self.LatexFolder, g) for g in getattr(self, "GraphicsPaths", [])]
        for folder in folders:
            for ext in IMAGE_EXTENSIONS:
                candidate = os.path.join(folder, path + ext)
                if os.path.isfile(candidate):
                    return candidate
        return None
